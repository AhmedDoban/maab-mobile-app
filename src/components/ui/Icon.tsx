export default function Icon({
  name,
  size = 20,
  tintColor,
  strokeWidth = 1.3,
}: {
  name: IconKey;
  size?: number;
  tintColor?: ColorValue;
  strokeWidth?: number;
}) {
  if (name === "tabQuran" || name === "quran") {
    return (
      <QuranCoverIcon size={size} color={tintColor} strokeWidth={strokeWidth} />
    );
  }

  return (
    <HugeiconsIcon
      icon={Icons[name]}
      size={size}
      color={tintColor as string | undefined}
      strokeWidth={strokeWidth}
    />
  );
}
